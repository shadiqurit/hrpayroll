-- Supplied HOD schema reference. Do not recreate an existing HOD table.
CREATE TABLE HOD
(
  ID        NUMBER,
  DEPT_ID   NUMBER,
  HOD_ID    NUMBER,
  STATUS    VARCHAR2(10 BYTE) DEFAULT 'ACTIVE',
  ENT_DATE  DATE DEFAULT SYSDATE,
  ENT_BY    NUMBER,
  UPD_DATE  DATE,
  UPD_BY    NUMBER
)
TABLESPACE HRMS
PCTUSED 0
PCTFREE 10
INITRANS 1
MAXTRANS 255
STORAGE
(
  INITIAL 64K
  NEXT 1M
  MINEXTENTS 1
  MAXEXTENTS UNLIMITED
  PCTINCREASE 0
  BUFFER_POOL DEFAULT
)
LOGGING
NOCOMPRESS
NOCACHE;

CREATE UNIQUE INDEX HOD_PK ON HOD (ID)
TABLESPACE HRMS
PCTFREE 10
INITRANS 2
MAXTRANS 255
STORAGE
(
  INITIAL 64K
  NEXT 1M
  MINEXTENTS 1
  MAXEXTENTS UNLIMITED
  PCTINCREASE 0
  BUFFER_POOL DEFAULT
);

ALTER TABLE HOD ADD (
  CONSTRAINT HOD_PK PRIMARY KEY (ID) USING INDEX HOD_PK ENABLE VALIDATE
);

CREATE OR REPLACE TRIGGER trg_hod_pk
    BEFORE INSERT OR UPDATE ON hod
    FOR EACH ROW
BEGIN
    IF :NEW.id IS NULL THEN
        SELECT NVL(MAX(id), 0) + 1 INTO :NEW.id FROM hod;
    END IF;
END trg_hod_pk;
/

ALTER TABLE HOD ADD (
  CONSTRAINT HOD_R01 FOREIGN KEY (HOD_ID) REFERENCES EMPLOYEES (ID) ENABLE VALIDATE,
  CONSTRAINT HOD_R02 FOREIGN KEY (DEPT_ID) REFERENCES DEPARTMENTS (ID) ENABLE VALIDATE
);
