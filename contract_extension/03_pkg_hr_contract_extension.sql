/* Manual extension: no scale, increment or benefit calculation.
   Package callers own the transaction; no COMMIT is performed here. */
CREATE OR REPLACE PACKAGE HRMS.PKG_HR_CONTRACT_EXTENSION AS
    PROCEDURE CREATE_DRAFT (
        P_EMP_ID IN NUMBER, P_CURRENT_FROM_DATE IN DATE,
        P_CURRENT_TO_DATE IN DATE, P_NEW_FROM_DATE IN DATE,
        P_NEW_TO_DATE IN DATE, P_USER_ID IN NUMBER, P_EXTENSION_ID OUT NUMBER);
    PROCEDURE CREATE_DUE_EXTENSION (
        P_EMP_ID IN NUMBER, P_SALARY_MODE IN VARCHAR2, P_TERM_MONTHS IN NUMBER,
        P_USER_ID IN NUMBER, P_EXTENSION_ID OUT NUMBER);
    PROCEDURE LOCK_DRAFT (
        P_EXTENSION_ID IN NUMBER, P_USER_ID IN NUMBER, P_EXPECTED_VERSION IN NUMBER);
    PROCEDURE SAVE_SALARY_ROW (
        P_EXTENSION_ID IN NUMBER, P_SALARY_ID IN OUT NUMBER, P_HEAD_ID IN NUMBER,
        P_NEW_AMOUNT IN NUMBER, P_INCLUDE_IN_LETTER IN VARCHAR2, P_USER_ID IN NUMBER);
    PROCEDURE SAVE_DRAFT (
        P_EXTENSION_ID IN NUMBER, P_NEW_FROM_DATE IN DATE, P_NEW_TO_DATE IN DATE,
        P_REASON IN VARCHAR2, P_REMARKS IN VARCHAR2, P_SPECIAL_TERMS IN CLOB,
        P_SIGNATORY_ID IN NUMBER, P_USER_ID IN NUMBER);
    PROCEDURE REFRESH_SALARY_SNAPSHOT (P_EXTENSION_ID IN NUMBER, P_USER_ID IN NUMBER);
    PROCEDURE FINAL_SUBMIT (
        P_EXTENSION_ID IN NUMBER, P_USER_ID IN NUMBER,
        P_ACTION_ID OUT NUMBER, P_LETTER_ID OUT NUMBER);
    PROCEDURE DELETE_DRAFT (P_EXTENSION_ID IN NUMBER, P_USER_ID IN NUMBER);
END PKG_HR_CONTRACT_EXTENSION;
/
SHOW ERRORS;

CREATE OR REPLACE PACKAGE BODY HRMS.PKG_HR_CONTRACT_EXTENSION AS
    PROCEDURE ASSERT_USER (P_USER_ID IN NUMBER) IS
    BEGIN
        IF P_USER_ID IS NULL THEN
            RAISE_APPLICATION_ERROR(-20700, 'Numeric authenticated USER_ID is required.');
        END IF;
    END;

    PROCEDURE ASSERT_NO_RENEWAL_DRAFT (P_EMP_ID IN NUMBER) IS
        L_COUNT PLS_INTEGER;
    BEGIN
        SELECT COUNT(*) INTO L_COUNT FROM HRMS.HR_CONTRACT_RENEWAL
         WHERE EMP_ID = P_EMP_ID AND STATUS = 'DRAFT';
        IF L_COUNT > 0 THEN
            RAISE_APPLICATION_ERROR(-20714,
                'This employee has a renewal draft. Finish or delete it before extending.');
        END IF;
    END;

    PROCEDURE ASSERT_ACCESS (P_EMP_ID IN NUMBER, P_USER_ID IN NUMBER) IS
        L_COUNT PLS_INTEGER;
    BEGIN
        ASSERT_USER(P_USER_ID);
        SELECT COUNT(*) INTO L_COUNT FROM HRMS.EMPLOYEES E
         WHERE E.ID = P_EMP_ID
           AND EXISTS (SELECT 1 FROM HRMS.USERS_COMPANY UC
                        WHERE UC.EMPID = P_USER_ID AND UC.COM_ID = E.COM_ID);
        IF L_COUNT <> 1 THEN
            RAISE_APPLICATION_ERROR(-20751, 'Employee is not in an authorized company.');
        END IF;
    END;

    PROCEDURE ASSERT_ELIGIBLE (P_EMP_ID IN NUMBER, P_TYPE OUT VARCHAR2) IS
        L_SEP_DATE DATE;
    BEGIN
        SELECT TRIM(EMP_TYPE), SEP_DATE INTO P_TYPE, L_SEP_DATE
          FROM HRMS.EMPLOYEES WHERE ID = P_EMP_ID FOR UPDATE NOWAIT;
        IF P_TYPE IS NULL OR P_TYPE NOT IN ('1', '3') THEN
            RAISE_APPLICATION_ERROR(-20713, 'Only probationary and contractual employees are eligible.');
        END IF;
        IF L_SEP_DATE IS NOT NULL AND TRUNC(L_SEP_DATE) <= TRUNC(SYSDATE) THEN
            RAISE_APPLICATION_ERROR(-20717, 'Separated employees cannot be extended.');
        END IF;
    EXCEPTION WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20717, 'Employee was not found.');
    END;

    FUNCTION HTML (P_VALUE IN VARCHAR2) RETURN VARCHAR2 IS
    BEGIN
        RETURN REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(P_VALUE,
            '&', '&amp;'), '<', '&lt;'), '>', '&gt;'), '"', '&quot;'), '''', '&#39;');
    END;

    PROCEDURE ASSERT_DATES (
        P_CURRENT_FROM IN DATE, P_CURRENT_TO IN DATE, P_NEW_FROM IN DATE, P_NEW_TO IN DATE
    ) IS
    BEGIN
        IF P_CURRENT_FROM IS NULL OR P_CURRENT_TO IS NULL
           OR P_NEW_FROM IS NULL OR P_NEW_TO IS NULL THEN
            RAISE_APPLICATION_ERROR(-20701, 'Current and extended start/end dates are required.');
        END IF;
        IF TRUNC(P_CURRENT_TO) < TRUNC(P_CURRENT_FROM)
           OR TRUNC(P_NEW_TO) < TRUNC(P_NEW_FROM) THEN
            RAISE_APPLICATION_ERROR(-20702, 'End date cannot be before start date.');
        END IF;
        IF TRUNC(P_NEW_FROM) <> TRUNC(P_CURRENT_TO) + 1 THEN
            RAISE_APPLICATION_ERROR(-20703, 'Extension must start the day after the current term ends.');
        END IF;
    END;

    PROCEDURE LOCK_DRAFT (
        P_EXTENSION_ID IN NUMBER, P_USER_ID IN NUMBER, P_EXPECTED_VERSION IN NUMBER
    ) IS
        L_STATUS VARCHAR2(20);
        L_VERSION NUMBER;
        L_EMP_ID NUMBER;
    BEGIN
        ASSERT_USER(P_USER_ID);
        SELECT STATUS, VERSION_NO, EMP_ID INTO L_STATUS, L_VERSION, L_EMP_ID
          FROM HRMS.HR_CONTRACT_EXTENSION
         WHERE EXTENSION_ID = P_EXTENSION_ID FOR UPDATE NOWAIT;
        ASSERT_ACCESS(L_EMP_ID, P_USER_ID);
        IF L_STATUS <> 'DRAFT' THEN
            RAISE_APPLICATION_ERROR(-20719, 'Only a draft extension can be edited.');
        END IF;
        IF P_EXPECTED_VERSION IS NOT NULL AND P_EXPECTED_VERSION <> L_VERSION THEN
            RAISE_APPLICATION_ERROR(-20721, 'This draft changed. Reload before saving.');
        END IF;
    EXCEPTION WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20720, 'Extension was not found.');
    END;

    PROCEDURE UPDATE_TOTALS (P_EXTENSION_ID IN NUMBER, P_USER_ID IN NUMBER) IS
        L_OLD_BASIC NUMBER;
        L_NEW_BASIC NUMBER;
        L_OLD_GROSS NUMBER;
        L_NEW_GROSS NUMBER;
        L_BAD_COUNT PLS_INTEGER;
    BEGIN
        SELECT COUNT(*) INTO L_BAD_COUNT
          FROM HRMS.HR_CONTRACT_EXTENSION_SALARY D
         WHERE D.EXTENSION_ID = P_EXTENSION_ID
           AND (D.NEW_AMOUNT IS NULL OR D.NEW_AMOUNT < 0
                OR D.NEW_AMOUNT > 9999999999.99
                OR D.NEW_AMOUNT <> ROUND(D.NEW_AMOUNT, 2)
                OR NOT EXISTS (
                    SELECT 1 FROM HRMS.ALLOWANCE_HEAD H WHERE H.HEAD_ID = D.SLNO
                      AND H.HEAD_CODE = D.HEADCODE AND H.HEAD_TYPE = D.HEAD_TYPE));
        IF L_BAD_COUNT > 0 THEN
            RAISE_APPLICATION_ERROR(-20710, 'Invalid salary amount or allowance head.');
        END IF;
        /* Salary structure and Basic are optional. Calculate totals only. */
        SELECT NVL(SUM(CASE WHEN LPAD(TRIM(HEADCODE), 3, '0') = '001' THEN OLD_AMOUNT ELSE 0 END), 0),
               NVL(SUM(CASE WHEN LPAD(TRIM(HEADCODE), 3, '0') = '001' THEN NEW_AMOUNT ELSE 0 END), 0),
               NVL(SUM(CASE WHEN HEAD_TYPE = 'EARNING' THEN OLD_AMOUNT ELSE 0 END), 0),
               NVL(SUM(CASE WHEN HEAD_TYPE = 'EARNING' THEN NEW_AMOUNT ELSE 0 END), 0)
          INTO L_OLD_BASIC, L_NEW_BASIC, L_OLD_GROSS, L_NEW_GROSS
          FROM HRMS.HR_CONTRACT_EXTENSION_SALARY WHERE EXTENSION_ID = P_EXTENSION_ID;
        UPDATE HRMS.HR_CONTRACT_EXTENSION
           SET OLD_BASIC = L_OLD_BASIC, NEW_BASIC = L_NEW_BASIC,
               OLD_GROSS = L_OLD_GROSS, NEW_GROSS = L_NEW_GROSS,
               UPDATED_BY = P_USER_ID, UPDATED_DATE = SYSDATE,
               VERSION_NO = VERSION_NO + 1
         WHERE EXTENSION_ID = P_EXTENSION_ID;
    END;

    PROCEDURE COPY_LIVE_SALARY (
        P_EXTENSION_ID IN NUMBER, P_EMP_ID IN NUMBER, P_USER_ID IN NUMBER
    ) IS
        L_BAD_COUNT PLS_INTEGER;
    BEGIN
        SELECT COUNT(*) INTO L_BAD_COUNT
          FROM HRMS.EMP_SALARY_STRUCTURE S
          LEFT JOIN HRMS.ALLOWANCE_HEAD H ON H.HEAD_ID = S.SLNO
         WHERE S.EMPLOYEE_ID = P_EMP_ID AND NVL(S.IS_ACTIVE, 'Y') = 'Y'
           AND (H.HEAD_ID IS NULL OR S.HEADCODE IS NULL
                OR S.HEADCODE <> H.HEAD_CODE OR NVL(S.AMOUNT, 0) < 0);
        IF L_BAD_COUNT > 0 THEN
            RAISE_APPLICATION_ERROR(-20711, 'Fix missing/mismatched live salary heads or negative amounts first.');
        END IF;
        INSERT INTO HRMS.HR_CONTRACT_EXTENSION_SALARY (
            EXTENSION_ID, EMP_ID, SALS_ID, SLNO, HEADCODE, HEAD_NAME, HEAD_TYPE,
            PRINT_ORDER, OLD_AMOUNT, NEW_AMOUNT, INCLUDE_IN_LETTER, IS_POSTED, CREATED_BY)
        SELECT P_EXTENSION_ID, P_EMP_ID, S.SALS_ID, S.SLNO, S.HEADCODE,
               H.HEAD_NAME, H.HEAD_TYPE, H.PRINT_ORDER, NVL(S.AMOUNT, 0), NVL(S.AMOUNT, 0),
               CASE WHEN H.HEAD_TYPE = 'EARNING' THEN 'Y' ELSE 'N' END, 'N', P_USER_ID
          FROM HRMS.EMP_SALARY_STRUCTURE S JOIN HRMS.ALLOWANCE_HEAD H ON H.HEAD_ID = S.SLNO
         WHERE S.EMPLOYEE_ID = P_EMP_ID AND NVL(S.IS_ACTIVE, 'Y') = 'Y';
    END;

    PROCEDURE CREATE_DRAFT (
        P_EMP_ID IN NUMBER, P_CURRENT_FROM_DATE IN DATE,
        P_CURRENT_TO_DATE IN DATE, P_NEW_FROM_DATE IN DATE,
        P_NEW_TO_DATE IN DATE, P_USER_ID IN NUMBER, P_EXTENSION_ID OUT NUMBER
    ) IS
        L_TYPE VARCHAR2(30);
        L_FROM DATE;
        L_TO DATE;
        L_GRADE NUMBER;
        L_SCALE NUMBER;
        L_STEP NUMBER;
        L_CONTRACT_STATUS VARCHAR2(20);
        L_BASELINE VARCHAR2(1) := 'N';
        L_SIGNATORY NUMBER;
        L_TEMPLATE NUMBER;
    BEGIN
        SAVEPOINT BEFORE_EXTENSION_CREATE;
        P_EXTENSION_ID := NULL;
        ASSERT_USER(P_USER_ID);
        ASSERT_ACCESS(P_EMP_ID, P_USER_ID);
        ASSERT_ELIGIBLE(P_EMP_ID, L_TYPE);
        ASSERT_NO_RENEWAL_DRAFT(P_EMP_ID);
        BEGIN
            SELECT CONTRACT_FROM_DATE, CONTRACT_TO_DATE, GRADE_ID, SCALE_ID, STEP_NO, CONTRACT_STATUS
              INTO L_FROM, L_TO, L_GRADE, L_SCALE, L_STEP, L_CONTRACT_STATUS
              FROM HRMS.HR_EMPLOYEE_CONTRACT WHERE EMP_ID = P_EMP_ID FOR UPDATE NOWAIT;
            IF L_CONTRACT_STATUS = 'CLOSED' THEN
                RAISE_APPLICATION_ERROR(-20742, 'A closed contract cannot be extended.');
            END IF;
        EXCEPTION WHEN NO_DATA_FOUND THEN
            L_FROM := TRUNC(P_CURRENT_FROM_DATE);
            L_TO := TRUNC(P_CURRENT_TO_DATE);
            IF L_TYPE = '1' THEN
                SELECT NVL(L_FROM, TRUNC(JOIN_DATE)), NVL(L_TO, TRUNC(CONFIRMATION_DUE_DATE))
                  INTO L_FROM, L_TO FROM HRMS.EMPLOYEES WHERE ID = P_EMP_ID;
            END IF;
            ASSERT_DATES(L_FROM, L_TO, P_NEW_FROM_DATE, P_NEW_TO_DATE);
            INSERT INTO HRMS.HR_EMPLOYEE_CONTRACT (
                EMP_ID, CONTRACT_FROM_DATE, CONTRACT_TO_DATE, CONTRACT_STATUS, CREATED_BY)
            VALUES (P_EMP_ID, L_FROM, L_TO, 'ACTIVE', P_USER_ID);
            L_BASELINE := 'Y';
        END;
        ASSERT_DATES(L_FROM, L_TO, P_NEW_FROM_DATE, P_NEW_TO_DATE);
        SELECT MIN(SIGNATORY_ID) KEEP (DENSE_RANK FIRST ORDER BY DISPLAY_ORDER, SIGNATORY_ID)
          INTO L_SIGNATORY FROM HRMS.HR_LETTER_SIGNATORY WHERE IS_ACTIVE = 'Y';
        SELECT TEMPLATE_ID INTO L_TEMPLATE FROM HRMS.HR_LETTER_TEMPLATE
         WHERE TEMPLATE_CODE = 'CONTRACT_EXTENSION_EN' AND ACTION_TYPE = 'CONTRACT_EXTENSION' AND IS_ACTIVE = 'Y';
        INSERT INTO HRMS.HR_CONTRACT_EXTENSION (
            EXTENSION_NO, EMP_ID, EMP_CODE_SNAPSHOT, EMP_NAME_SNAPSHOT, EMP_TYPE_SNAPSHOT,
            DESIGNATION_SNAPSHOT, DEPARTMENT_SNAPSHOT, LOCATION_SNAPSHOT,
            ADDRESS_SNAPSHOT, COMPANY_SNAPSHOT, GRADE_SNAPSHOT,
            CURRENT_FROM_DATE, CURRENT_TO_DATE, NEW_FROM_DATE, NEW_TO_DATE,
            OLD_GRADE_ID, NEW_GRADE_ID, OLD_SCALE_ID, NEW_SCALE_ID, OLD_STEP_NO, NEW_STEP_NO,
            SALARY_MODE, SIGNATORY_ID, TEMPLATE_ID, BASELINE_CREATED_YN, CREATED_BY)
        SELECT NULL, E.ID, E.EMP_ID, TRIM(E.F_NAME || ' ' || E.L_NAME), L_TYPE,
               D.DESIGNATION, DP.DEPT_NAME, L.NAME, E.ADDRESS, C.NAME, E.GRADE,
               L_FROM, L_TO, TRUNC(P_NEW_FROM_DATE), TRUNC(P_NEW_TO_DATE),
               L_GRADE, L_GRADE, L_SCALE, L_SCALE, L_STEP, L_STEP,
               'MANUAL', L_SIGNATORY, L_TEMPLATE, L_BASELINE, P_USER_ID
          FROM HRMS.EMPLOYEES E
          LEFT JOIN HRMS.DESIGNATIONS D ON D.ID = E.DESIG_ID
          LEFT JOIN HRMS.DEPARTMENTS DP ON DP.ID = E.DEPT_ID
          LEFT JOIN HRMS.LOCATIONS L ON L.ID = E.LOC_ID
          LEFT JOIN HRMS.COMPANY C ON C.ID = E.COM_ID WHERE E.ID = P_EMP_ID;
        SELECT EXTENSION_ID INTO P_EXTENSION_ID FROM HRMS.HR_CONTRACT_EXTENSION
         WHERE EMP_ID = P_EMP_ID AND STATUS = 'DRAFT';
        COPY_LIVE_SALARY(P_EXTENSION_ID, P_EMP_ID, P_USER_ID);
        UPDATE_TOTALS(P_EXTENSION_ID, P_USER_ID);
        INSERT INTO HRMS.HR_CONTRACT_EXT_RECIPIENT (
            EXTENSION_ID, SECTION_TYPE, LETTER_RECIPIENT_ID, DISPLAY_ORDER, IS_ACTIVE, CREATED_BY)
        SELECT P_EXTENSION_ID, 'COPY', LETTER_RECIPIENT_ID, DISPLAY_ORDER, 'Y', P_USER_ID
          FROM HRMS.HR_LETTER_RECIPIENT
         WHERE IS_ACTIVE = 'Y' AND RECIPIENT_CODE IN ('PERSONAL_FILE', 'OFFICE_COPY');
    EXCEPTION
        WHEN DUP_VAL_ON_INDEX THEN
            ROLLBACK TO BEFORE_EXTENSION_CREATE;
            P_EXTENSION_ID := NULL;
            RAISE_APPLICATION_ERROR(-20714, 'This employee already has a extension draft.');
        WHEN OTHERS THEN
            ROLLBACK TO BEFORE_EXTENSION_CREATE;
            P_EXTENSION_ID := NULL;
            RAISE;
    END;

    PROCEDURE CREATE_DUE_EXTENSION (
        P_EMP_ID IN NUMBER, P_SALARY_MODE IN VARCHAR2, P_TERM_MONTHS IN NUMBER,
        P_USER_ID IN NUMBER, P_EXTENSION_ID OUT NUMBER
    ) IS
        L_FROM DATE;
        L_TO DATE;
        L_NEW_FROM DATE;
    BEGIN
        IF NVL(UPPER(TRIM(P_SALARY_MODE)), 'MANUAL') <> 'MANUAL' THEN
            RAISE_APPLICATION_ERROR(-20740, 'Only manual changes are allowed.');
        END IF;
        IF P_TERM_MONTHS IS NULL OR P_TERM_MONTHS <> TRUNC(P_TERM_MONTHS)
           OR P_TERM_MONTHS < 1 OR P_TERM_MONTHS > 60 THEN
            RAISE_APPLICATION_ERROR(-20741, 'Extension term must be 1 to 60 whole months.');
        END IF;
        SELECT NVL(C.CONTRACT_FROM_DATE, CASE WHEN TRIM(E.EMP_TYPE) = '1' THEN E.JOIN_DATE END),
               NVL(C.CONTRACT_TO_DATE, CASE WHEN TRIM(E.EMP_TYPE) = '1' THEN E.CONFIRMATION_DUE_DATE END)
          INTO L_FROM, L_TO FROM HRMS.EMPLOYEES E
          LEFT JOIN HRMS.HR_EMPLOYEE_CONTRACT C ON C.EMP_ID = E.ID WHERE E.ID = P_EMP_ID;
        L_NEW_FROM := TRUNC(L_TO) + 1;
        CREATE_DRAFT(P_EMP_ID, L_FROM, L_TO, L_NEW_FROM,
                     ADD_MONTHS(L_NEW_FROM, P_TERM_MONTHS) - 1, P_USER_ID, P_EXTENSION_ID);
    END;

    PROCEDURE SAVE_SALARY_ROW (
        P_EXTENSION_ID IN NUMBER, P_SALARY_ID IN OUT NUMBER, P_HEAD_ID IN NUMBER,
        P_NEW_AMOUNT IN NUMBER, P_INCLUDE_IN_LETTER IN VARCHAR2, P_USER_ID IN NUMBER
    ) IS
        L_EMP_ID NUMBER;
        L_TYPE VARCHAR2(30);
        L_HEAD HRMS.ALLOWANCE_HEAD%ROWTYPE;
        L_COUNT PLS_INTEGER;
    BEGIN
        LOCK_DRAFT(P_EXTENSION_ID, P_USER_ID, NULL);
        SELECT EMP_ID INTO L_EMP_ID FROM HRMS.HR_CONTRACT_EXTENSION WHERE EXTENSION_ID = P_EXTENSION_ID;
        ASSERT_ELIGIBLE(L_EMP_ID, L_TYPE);
        IF P_NEW_AMOUNT IS NULL OR P_NEW_AMOUNT < 0 OR P_NEW_AMOUNT > 9999999999.99
           OR P_NEW_AMOUNT <> ROUND(P_NEW_AMOUNT, 2) THEN
            RAISE_APPLICATION_ERROR(-20710, 'Enter a non-negative amount with at most two decimal places.');
        END IF;
        IF P_INCLUDE_IN_LETTER IS NULL OR P_INCLUDE_IN_LETTER NOT IN ('Y', 'N') THEN
            RAISE_APPLICATION_ERROR(-20710, 'Include in letter must be Y or N.');
        END IF;
        IF P_SALARY_ID IS NOT NULL THEN
            UPDATE HRMS.HR_CONTRACT_EXTENSION_SALARY
               SET NEW_AMOUNT = P_NEW_AMOUNT, INCLUDE_IN_LETTER = P_INCLUDE_IN_LETTER,
                   UPDATED_BY = P_USER_ID, UPDATED_DATE = SYSDATE
             WHERE EXTENSION_SALARY_ID = P_SALARY_ID AND EXTENSION_ID = P_EXTENSION_ID
               AND EMP_ID = L_EMP_ID AND SLNO = P_HEAD_ID AND IS_POSTED = 'N';
            IF SQL%ROWCOUNT <> 1 THEN
                RAISE_APPLICATION_ERROR(-20710, 'Salary row not found or its head was changed.');
            END IF;
        ELSE
            SELECT * INTO L_HEAD FROM HRMS.ALLOWANCE_HEAD WHERE HEAD_ID = P_HEAD_ID AND IS_ACTIVE = 'Y';
            SELECT COUNT(*) INTO L_COUNT FROM HRMS.EMP_SALARY_STRUCTURE
             WHERE EMPLOYEE_ID = L_EMP_ID AND SLNO = P_HEAD_ID;
            IF L_COUNT > 0 THEN
                RAISE_APPLICATION_ERROR(-20731, 'This head already exists. Refresh salary or review its inactive record.');
            END IF;
            INSERT INTO HRMS.HR_CONTRACT_EXTENSION_SALARY (
                EXTENSION_ID, EMP_ID, SLNO, HEADCODE, HEAD_NAME, HEAD_TYPE, PRINT_ORDER,
                OLD_AMOUNT, NEW_AMOUNT, INCLUDE_IN_LETTER, CREATED_BY)
            VALUES (P_EXTENSION_ID, L_EMP_ID, L_HEAD.HEAD_ID, L_HEAD.HEAD_CODE,
                L_HEAD.HEAD_NAME, L_HEAD.HEAD_TYPE, L_HEAD.PRINT_ORDER,
                0, P_NEW_AMOUNT, P_INCLUDE_IN_LETTER, P_USER_ID)
            RETURNING EXTENSION_SALARY_ID INTO P_SALARY_ID;
        END IF;
    END;

    PROCEDURE SAVE_DRAFT (
        P_EXTENSION_ID IN NUMBER, P_NEW_FROM_DATE IN DATE, P_NEW_TO_DATE IN DATE,
        P_REASON IN VARCHAR2, P_REMARKS IN VARCHAR2, P_SPECIAL_TERMS IN CLOB,
        P_SIGNATORY_ID IN NUMBER, P_USER_ID IN NUMBER
    ) IS
        L_ROW HRMS.HR_CONTRACT_EXTENSION%ROWTYPE;
        L_TYPE VARCHAR2(30);
    BEGIN
        LOCK_DRAFT(P_EXTENSION_ID, P_USER_ID, NULL);
        SELECT * INTO L_ROW FROM HRMS.HR_CONTRACT_EXTENSION WHERE EXTENSION_ID = P_EXTENSION_ID;
        ASSERT_ELIGIBLE(L_ROW.EMP_ID, L_TYPE);
        ASSERT_NO_RENEWAL_DRAFT(L_ROW.EMP_ID);
        IF L_ROW.SALARY_MODE <> 'MANUAL' THEN
            RAISE_APPLICATION_ERROR(-20740, 'Only manual changes are allowed for extensions.');
        END IF;
        IF L_ROW.EMP_TYPE_SNAPSHOT IS NULL THEN
            RAISE_APPLICATION_ERROR(-20729, 'Employee type is missing. Prepare a new extension draft.');
        ELSIF L_ROW.EMP_TYPE_SNAPSHOT <> L_TYPE THEN
            RAISE_APPLICATION_ERROR(-20729, 'Employee type changed. Delete the draft and prepare again.');
        END IF;
        ASSERT_DATES(L_ROW.CURRENT_FROM_DATE, L_ROW.CURRENT_TO_DATE, P_NEW_FROM_DATE, P_NEW_TO_DATE);
        IF DBMS_LOB.GETLENGTH(P_SPECIAL_TERMS) > 4000 THEN
            RAISE_APPLICATION_ERROR(-20710, 'Additional terms must be at most 4000 characters.');
        END IF;
        UPDATE HRMS.HR_CONTRACT_EXTENSION
           SET NEW_FROM_DATE = TRUNC(P_NEW_FROM_DATE), NEW_TO_DATE = TRUNC(P_NEW_TO_DATE),
               REASON = P_REASON, REMARKS = P_REMARKS, SPECIAL_TERMS = P_SPECIAL_TERMS,
               SIGNATORY_ID = P_SIGNATORY_ID, EMP_TYPE_SNAPSHOT = L_TYPE
         WHERE EXTENSION_ID = P_EXTENSION_ID;
        UPDATE_TOTALS(P_EXTENSION_ID, P_USER_ID);
    END;

    PROCEDURE REFRESH_SALARY_SNAPSHOT (P_EXTENSION_ID IN NUMBER, P_USER_ID IN NUMBER) IS
        L_ROW HRMS.HR_CONTRACT_EXTENSION%ROWTYPE;
        L_TYPE VARCHAR2(30);
    BEGIN
        SAVEPOINT BEFORE_EXTENSION_REFRESH;
        LOCK_DRAFT(P_EXTENSION_ID, P_USER_ID, NULL);
        SELECT * INTO L_ROW FROM HRMS.HR_CONTRACT_EXTENSION WHERE EXTENSION_ID = P_EXTENSION_ID;
        ASSERT_ELIGIBLE(L_ROW.EMP_ID, L_TYPE);
        IF L_ROW.EMP_TYPE_SNAPSHOT IS NOT NULL AND L_ROW.EMP_TYPE_SNAPSHOT <> L_TYPE THEN
            RAISE_APPLICATION_ERROR(-20729, 'Employee type changed. Delete the draft and prepare again.');
        END IF;
        DELETE FROM HRMS.HR_CONTRACT_EXTENSION_SALARY WHERE EXTENSION_ID = P_EXTENSION_ID;
        COPY_LIVE_SALARY(P_EXTENSION_ID, L_ROW.EMP_ID, P_USER_ID);
        UPDATE HRMS.HR_CONTRACT_EXTENSION
           SET SALARY_MODE = 'MANUAL', NEW_GRADE_ID = OLD_GRADE_ID,
               NEW_SCALE_ID = OLD_SCALE_ID, NEW_STEP_NO = OLD_STEP_NO,
               EMP_TYPE_SNAPSHOT = L_TYPE,
               TEMPLATE_ID = (SELECT TEMPLATE_ID FROM HRMS.HR_LETTER_TEMPLATE
                               WHERE TEMPLATE_CODE = 'CONTRACT_EXTENSION_EN'
                                 AND IS_ACTIVE = 'Y' AND ACTION_TYPE = 'CONTRACT_EXTENSION')
         WHERE EXTENSION_ID = P_EXTENSION_ID;
        UPDATE_TOTALS(P_EXTENSION_ID, P_USER_ID);
    EXCEPTION WHEN OTHERS THEN
        ROLLBACK TO BEFORE_EXTENSION_REFRESH;
        RAISE;
    END;

    PROCEDURE GENERATE_LETTER (
        P_EXTENSION_ID IN NUMBER, P_ACTION_ID IN NUMBER, P_USER_ID IN NUMBER, P_LETTER_ID OUT NUMBER
    ) IS
        L_ROW HRMS.HR_CONTRACT_EXTENSION%ROWTYPE;
        L_TEMPLATE NUMBER;
        L_SUBJECT VARCHAR2(500);
        L_BODY CLOB;
        L_COUNT PLS_INTEGER;
    BEGIN
        SELECT * INTO L_ROW FROM HRMS.HR_CONTRACT_EXTENSION WHERE EXTENSION_ID = P_EXTENSION_ID;
        SELECT COUNT(*) INTO L_COUNT FROM HRMS.HR_LETTER_SIGNATORY
         WHERE SIGNATORY_ID = L_ROW.SIGNATORY_ID AND IS_ACTIVE = 'Y';
        IF L_COUNT <> 1 THEN
            RAISE_APPLICATION_ERROR(-20722, 'An active letter signatory is required.');
        END IF;
        SELECT TEMPLATE_ID, SUBJECT_TEMPLATE, BODY_TEMPLATE INTO L_TEMPLATE, L_SUBJECT, L_BODY
          FROM HRMS.HR_LETTER_TEMPLATE WHERE TEMPLATE_CODE = 'CONTRACT_EXTENSION_EN'
           AND ACTION_TYPE = 'CONTRACT_EXTENSION' AND IS_ACTIVE = 'Y';
        L_BODY := REPLACE(L_BODY, '#EMP_NAME#', HTML(L_ROW.EMP_NAME_SNAPSHOT));
        L_BODY := REPLACE(L_BODY, '#COMPANY_NAME#', HTML(L_ROW.COMPANY_SNAPSHOT));
        L_BODY := REPLACE(L_BODY, '#EMPLOYMENT_TYPE#',
                         CASE L_ROW.EMP_TYPE_SNAPSHOT WHEN '1' THEN 'probationary' ELSE 'contractual' END);
        L_BODY := REPLACE(L_BODY, '#NEW_FROM_DATE#',
                         TO_CHAR(L_ROW.NEW_FROM_DATE, 'DD Month YYYY', 'NLS_DATE_LANGUAGE=English'));
        L_BODY := REPLACE(L_BODY, '#NEW_TO_DATE#',
                         TO_CHAR(L_ROW.NEW_TO_DATE, 'DD Month YYYY', 'NLS_DATE_LANGUAGE=English'));
        L_BODY := REPLACE(L_BODY, '#SPECIAL_TERMS#',
                         REPLACE(HTML(DBMS_LOB.SUBSTR(L_ROW.SPECIAL_TERMS, 4000, 1)), CHR(10), '<br>'));
        INSERT INTO HRMS.HR_EMPLOYEE_LETTER (
            EMP_ID, ACTION_ID, CONTRACT_EXTENSION_ID, TEMPLATE_ID, LETTER_NO, LETTER_DATE,
            SUBJECT_TEXT, BODY_HTML, STATUS, GENERATED_BY, GENERATED_DATE,
            APPROVED_BY, APPROVED_DATE, ISSUED_BY, ISSUED_DATE)
        VALUES (L_ROW.EMP_ID, P_ACTION_ID, P_EXTENSION_ID, L_TEMPLATE, L_ROW.EXTENSION_NO, SYSDATE,
            L_SUBJECT, L_BODY, 'ISSUED', P_USER_ID, SYSDATE, P_USER_ID, SYSDATE, P_USER_ID, SYSDATE)
        RETURNING LETTER_ID INTO P_LETTER_ID;
        UPDATE HRMS.HR_CONTRACT_EXTENSION SET TEMPLATE_ID = L_TEMPLATE WHERE EXTENSION_ID = P_EXTENSION_ID;
    END;

    PROCEDURE FINAL_SUBMIT (
        P_EXTENSION_ID IN NUMBER, P_USER_ID IN NUMBER, P_ACTION_ID OUT NUMBER, P_LETTER_ID OUT NUMBER
    ) IS
        L_ROW HRMS.HR_CONTRACT_EXTENSION%ROWTYPE;
        L_CONTRACT HRMS.HR_EMPLOYEE_CONTRACT%ROWTYPE;
        L_TYPE VARCHAR2(30);
        L_COUNT PLS_INTEGER;
        L_SALS_ID NUMBER;
    BEGIN
        SAVEPOINT BEFORE_CONTRACT_POST;
        P_ACTION_ID := NULL;
        P_LETTER_ID := NULL;
        LOCK_DRAFT(P_EXTENSION_ID, P_USER_ID, NULL);
        SELECT * INTO L_ROW FROM HRMS.HR_CONTRACT_EXTENSION WHERE EXTENSION_ID = P_EXTENSION_ID;
        ASSERT_ELIGIBLE(L_ROW.EMP_ID, L_TYPE);
        ASSERT_NO_RENEWAL_DRAFT(L_ROW.EMP_ID);
        IF L_ROW.SALARY_MODE <> 'MANUAL' THEN
            RAISE_APPLICATION_ERROR(-20740, 'Only manual changes are allowed for extensions.');
        END IF;
        IF L_ROW.EMP_TYPE_SNAPSHOT IS NULL OR L_ROW.EMP_TYPE_SNAPSHOT <> L_TYPE THEN
            RAISE_APPLICATION_ERROR(-20729, 'Employee type changed or is missing. Prepare a fresh draft.');
        END IF;
        ASSERT_DATES(L_ROW.CURRENT_FROM_DATE, L_ROW.CURRENT_TO_DATE, L_ROW.NEW_FROM_DATE, L_ROW.NEW_TO_DATE);
        IF L_ROW.NEW_FROM_DATE > TRUNC(SYSDATE) THEN
            RAISE_APPLICATION_ERROR(-20727, 'Final submit is allowed on or after the extended start date.');
        END IF;
        SELECT * INTO L_CONTRACT FROM HRMS.HR_EMPLOYEE_CONTRACT WHERE EMP_ID = L_ROW.EMP_ID FOR UPDATE NOWAIT;
        IF L_CONTRACT.CONTRACT_STATUS = 'CLOSED'
           OR L_CONTRACT.CONTRACT_FROM_DATE <> L_ROW.CURRENT_FROM_DATE
           OR L_CONTRACT.CONTRACT_TO_DATE <> L_ROW.CURRENT_TO_DATE
           OR NVL(L_CONTRACT.GRADE_ID, -1) <> NVL(L_ROW.OLD_GRADE_ID, -1)
           OR NVL(L_CONTRACT.SCALE_ID, -1) <> NVL(L_ROW.OLD_SCALE_ID, -1)
           OR NVL(L_CONTRACT.STEP_NO, -1) <> NVL(L_ROW.OLD_STEP_NO, -1) THEN
            RAISE_APPLICATION_ERROR(-20729, 'Current contract changed. Delete the draft and prepare again.');
        END IF;
        FOR S IN (SELECT SALS_ID FROM HRMS.EMP_SALARY_STRUCTURE
                   WHERE EMPLOYEE_ID = L_ROW.EMP_ID FOR UPDATE NOWAIT) LOOP
            NULL;
        END LOOP;
        /* Compare live salary in both directions, including head identity. */
        SELECT COUNT(*) INTO L_COUNT FROM HRMS.EMP_SALARY_STRUCTURE S
         WHERE S.EMPLOYEE_ID = L_ROW.EMP_ID AND NVL(S.IS_ACTIVE, 'Y') = 'Y'
           AND NOT EXISTS (SELECT 1 FROM HRMS.HR_CONTRACT_EXTENSION_SALARY D
                            WHERE D.EXTENSION_ID = P_EXTENSION_ID AND D.EMP_ID = S.EMPLOYEE_ID
                              AND D.SALS_ID = S.SALS_ID AND D.SLNO = S.SLNO
                              AND D.HEADCODE = S.HEADCODE AND D.OLD_AMOUNT = NVL(S.AMOUNT, 0));
        IF L_COUNT > 0 THEN
            RAISE_APPLICATION_ERROR(-20730, 'Live salary changed. Refresh salary and review again.');
        END IF;
        SELECT COUNT(*) INTO L_COUNT FROM HRMS.HR_CONTRACT_EXTENSION_SALARY D
         WHERE D.EXTENSION_ID = P_EXTENSION_ID
           AND (D.EMP_ID <> L_ROW.EMP_ID
                OR (D.SALS_ID IS NOT NULL AND NOT EXISTS (
                    SELECT 1 FROM HRMS.EMP_SALARY_STRUCTURE S
                     WHERE S.SALS_ID = D.SALS_ID AND S.EMPLOYEE_ID = D.EMP_ID
                       AND NVL(S.IS_ACTIVE, 'Y') = 'Y' AND S.SLNO = D.SLNO
                       AND S.HEADCODE = D.HEADCODE AND NVL(S.AMOUNT, 0) = D.OLD_AMOUNT))
                OR (D.SALS_ID IS NULL AND EXISTS (
                    SELECT 1 FROM HRMS.EMP_SALARY_STRUCTURE S
                     WHERE S.EMPLOYEE_ID = D.EMP_ID AND S.SLNO = D.SLNO)));
        IF L_COUNT > 0 THEN
            RAISE_APPLICATION_ERROR(-20730, 'A salary snapshot changed or a manual head now conflicts. Refresh salary.');
        END IF;
        UPDATE_TOTALS(P_EXTENSION_ID, P_USER_ID);
        SELECT * INTO L_ROW FROM HRMS.HR_CONTRACT_EXTENSION WHERE EXTENSION_ID = P_EXTENSION_ID;
        INSERT INTO HRMS.HR_EMPLOYEE_ACTION (
            EMP_ID, ACTION_TYPE, ACTION_DATE, EFFECTIVE_DATE, OLD_BASIC, NEW_BASIC,
            OLD_GROSS, NEW_GROSS, INCREMENT_AMOUNT, INCREMENT_PERCENT,
            REASON, REMARKS, APPROVAL_STATUS, ENT_BY, ENT_DATE, APPROVED_BY, APPROVED_DATE)
        VALUES (L_ROW.EMP_ID, 'CONTRACT_EXTENSION', SYSDATE, L_ROW.NEW_FROM_DATE,
            L_ROW.OLD_BASIC, L_ROW.NEW_BASIC, L_ROW.OLD_GROSS, L_ROW.NEW_GROSS,
            L_ROW.NEW_BASIC - L_ROW.OLD_BASIC,
            CASE WHEN L_ROW.OLD_BASIC = 0 THEN NULL ELSE
                ROUND((L_ROW.NEW_BASIC - L_ROW.OLD_BASIC) / L_ROW.OLD_BASIC * 100, 2) END,
            NVL(L_ROW.REASON, 'Contract extension'), L_ROW.REMARKS, 'APPROVED',
            P_USER_ID, SYSDATE, P_USER_ID, SYSDATE)
        RETURNING ACTION_ID INTO P_ACTION_ID;
        FOR D IN (SELECT * FROM HRMS.HR_CONTRACT_EXTENSION_SALARY WHERE EXTENSION_ID = P_EXTENSION_ID ORDER BY SLNO) LOOP
            IF D.SALS_ID IS NOT NULL THEN
                /* Unchanged salary rows are never updated or revised. */
                IF D.NEW_AMOUNT <> D.OLD_AMOUNT THEN
                    UPDATE HRMS.EMP_SALARY_STRUCTURE SET AMOUNT = D.NEW_AMOUNT, REVISION_TYPE = 'R',
                        UPDATED_BY = P_USER_ID, UPDATED_DATE = SYSDATE
                     WHERE SALS_ID = D.SALS_ID AND EMPLOYEE_ID = L_ROW.EMP_ID;
                END IF;
            ELSIF D.NEW_AMOUNT > 0 THEN
                INSERT INTO HRMS.EMP_SALARY_STRUCTURE (
                    EMPLOYEE_ID, SLNO, HEADCODE, AMOUNT, REVISION_TYPE, IS_ACTIVE, CREATED_BY, CREATED_DATE)
                VALUES (L_ROW.EMP_ID, D.SLNO, D.HEADCODE, D.NEW_AMOUNT, 'R', 'Y', P_USER_ID, SYSDATE)
                RETURNING SALS_ID INTO L_SALS_ID;
                UPDATE HRMS.HR_CONTRACT_EXTENSION_SALARY SET SALS_ID = L_SALS_ID
                 WHERE EXTENSION_SALARY_ID = D.EXTENSION_SALARY_ID;
            END IF;
        END LOOP;
        UPDATE HRMS.HR_EMPLOYEE_CONTRACT
           SET CONTRACT_FROM_DATE = L_ROW.NEW_FROM_DATE, CONTRACT_TO_DATE = L_ROW.NEW_TO_DATE,
               CONTRACT_STATUS = 'ACTIVE',
               UPDATED_BY = P_USER_ID, UPDATED_DATE = SYSDATE WHERE EMP_ID = L_ROW.EMP_ID;
        IF L_TYPE = '1' THEN
            UPDATE HRMS.EMPLOYEES SET CONFIRMATION_DUE_DATE = L_ROW.NEW_TO_DATE,
                UPD_BY = P_USER_ID, UPD_DATE = SYSDATE WHERE ID = L_ROW.EMP_ID;
        END IF;
        GENERATE_LETTER(P_EXTENSION_ID, P_ACTION_ID, P_USER_ID, P_LETTER_ID);
        UPDATE HRMS.HR_CONTRACT_EXTENSION_SALARY SET IS_POSTED = 'Y', POSTED_BY = P_USER_ID, POSTED_DATE = SYSDATE
         WHERE EXTENSION_ID = P_EXTENSION_ID;
        UPDATE HRMS.HR_CONTRACT_EXTENSION
           SET ACTION_ID = P_ACTION_ID, LETTER_ID = P_LETTER_ID, STATUS = 'POSTED',
               POSTED_BY = P_USER_ID, POSTED_DATE = SYSDATE, UPDATED_BY = P_USER_ID,
               UPDATED_DATE = SYSDATE, VERSION_NO = VERSION_NO + 1 WHERE EXTENSION_ID = P_EXTENSION_ID;
    EXCEPTION WHEN OTHERS THEN
        ROLLBACK TO BEFORE_CONTRACT_POST;
        P_ACTION_ID := NULL;
        P_LETTER_ID := NULL;
        RAISE;
    END;

    PROCEDURE DELETE_DRAFT (P_EXTENSION_ID IN NUMBER, P_USER_ID IN NUMBER) IS
        L_ROW HRMS.HR_CONTRACT_EXTENSION%ROWTYPE;
        L_EMP_ID NUMBER;
    BEGIN
        LOCK_DRAFT(P_EXTENSION_ID, P_USER_ID, NULL);
        SELECT * INTO L_ROW FROM HRMS.HR_CONTRACT_EXTENSION WHERE EXTENSION_ID = P_EXTENSION_ID;
        SELECT ID INTO L_EMP_ID FROM HRMS.EMPLOYEES WHERE ID = L_ROW.EMP_ID FOR UPDATE NOWAIT;
        DELETE FROM HRMS.HR_CONTRACT_EXTENSION WHERE EXTENSION_ID = P_EXTENSION_ID;
        /* Retain the shared current contract when an extension draft is deleted. */
    END;
END PKG_HR_CONTRACT_EXTENSION;
