CREATE TABLE HRMS.HR_EMPLOYEE_CONTRACT
(
    EMP_ID               NUMBER NOT NULL,
    CONTRACT_FROM_DATE   DATE NOT NULL,
    CONTRACT_TO_DATE     DATE NOT NULL,
    GRADE_ID             NUMBER,
    SCALE_ID             NUMBER,
    STEP_NO              NUMBER(3),
    LATEST_RENEWAL_ID    NUMBER,
    CONTRACT_STATUS      VARCHAR2(20 BYTE) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_BY           NUMBER,
    CREATED_DATE         DATE DEFAULT SYSDATE NOT NULL,
    UPDATED_BY           NUMBER,
    UPDATED_DATE         DATE,
    CONSTRAINT PK_HR_EMP_CONTRACT PRIMARY KEY (EMP_ID),
    CONSTRAINT FK_HR_EMP_CONTRACT_EMP FOREIGN KEY (EMP_ID)
        REFERENCES HRMS.EMPLOYEES (ID),
    CONSTRAINT FK_HR_EMP_CONTRACT_GRADE FOREIGN KEY (GRADE_ID)
        REFERENCES HRMS.JOB_GRADES (ID),
    CONSTRAINT FK_HR_EMP_CONTRACT_SCALE FOREIGN KEY (SCALE_ID)
        REFERENCES HRMS.PAY_SCALE_MASTER (SCALE_ID),
    CONSTRAINT CK_HR_EMP_CONTRACT_DATES CHECK
        (CONTRACT_TO_DATE >= CONTRACT_FROM_DATE),
    CONSTRAINT CK_HR_EMP_CONTRACT_STATUS CHECK
        (CONTRACT_STATUS IN ('ACTIVE', 'EXPIRED', 'CLOSED')),
    CONSTRAINT CK_HR_EMP_CONTRACT_STEP CHECK
        (STEP_NO IS NULL OR STEP_NO BETWEEN 0 AND 25)
);

CREATE INDEX HRMS.IX_HR_EMP_CONTRACT_DUE
    ON HRMS.HR_EMPLOYEE_CONTRACT (CONTRACT_STATUS, CONTRACT_TO_DATE);


CREATE TABLE HRMS.HR_CONTRACT_RENEWAL
(
    RENEWAL_ID            NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    RENEWAL_NO            VARCHAR2(30 BYTE) NOT NULL,
    EMP_ID                NUMBER NOT NULL,
    ACTION_ID             NUMBER,
    LETTER_ID             NUMBER,

    EMP_CODE_SNAPSHOT     VARCHAR2(30 CHAR) NOT NULL,
    EMP_NAME_SNAPSHOT     VARCHAR2(200 CHAR) NOT NULL,
    DESIGNATION_SNAPSHOT  VARCHAR2(150 CHAR),
    DEPARTMENT_SNAPSHOT   VARCHAR2(150 CHAR),
    LOCATION_SNAPSHOT     VARCHAR2(150 CHAR),
    ADDRESS_SNAPSHOT      VARCHAR2(500 CHAR),
    COMPANY_SNAPSHOT      VARCHAR2(200 CHAR),
    GRADE_SNAPSHOT        VARCHAR2(100 CHAR),
    PAY_SCALE_SNAPSHOT    VARCHAR2(300 CHAR),

    CURRENT_FROM_DATE     DATE NOT NULL,
    CURRENT_TO_DATE       DATE NOT NULL,
    NEW_FROM_DATE         DATE NOT NULL,
    NEW_TO_DATE           DATE NOT NULL,

    OLD_GRADE_ID          NUMBER,
    NEW_GRADE_ID          NUMBER NOT NULL,
    OLD_SCALE_ID          NUMBER,
    NEW_SCALE_ID          NUMBER NOT NULL,
    OLD_STEP_NO           NUMBER(3),
    NEW_STEP_NO           NUMBER(3) NOT NULL,

    OLD_BASIC             NUMBER(14,2),
    NEW_BASIC             NUMBER(14,2),
    OLD_GROSS             NUMBER(14,2),
    NEW_GROSS             NUMBER(14,2),

    REASON                VARCHAR2(1000 CHAR),
    REMARKS               VARCHAR2(1000 CHAR),
    SPECIAL_TERMS         CLOB,
    SIGNATORY_ID          NUMBER,
    TEMPLATE_ID           NUMBER,
    APPROVAL_STATUS       VARCHAR2(20 BYTE) DEFAULT 'DRAFT' NOT NULL,
    VERSION_NO            NUMBER DEFAULT 0 NOT NULL,

    PREPARED_BY           NUMBER,
    PREPARED_DATE         DATE DEFAULT SYSDATE NOT NULL,
    SUBMITTED_BY          NUMBER,
    SUBMITTED_DATE        DATE,
    APPROVED_BY           NUMBER,
    APPROVED_DATE         DATE,
    POSTED_BY             NUMBER,
    POSTED_DATE           DATE,
    CANCELLED_BY          NUMBER,
    CANCELLED_DATE        DATE,
    CREATED_BY            NUMBER,
